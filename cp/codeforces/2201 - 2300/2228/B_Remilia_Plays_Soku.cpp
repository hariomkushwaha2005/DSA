inline void fast_io() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
}

void solve() {
    int n, x, y, k;
    cin >> n >> x >> y >> k;

    int dist = abs(x - y);
    dist = min(dist, n - dist);

    if(n <= 3) cout << dist << endl;
    else{
        cout << dist + k << endl;
    }
}

int main() {
    fast_io();
    
    int t = 1;
    cin >> t;
    while (t--) {
        solve();
    }
    
    return 0;
}