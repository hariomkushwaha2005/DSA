#define all(x) (x).begin(), (x).end()

inline void fast_io()
{
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
}

void solve()
{
    vll v(3);
    for (int i = 0; i < 3; ++i)
        cin >> v[i];
    

    sort(all(v));

    cout << min(v[2] - v[1], v[1] - v[0]) << endl;
}

int main()
{
    fast_io();

    int t = 1;
    cin >> t;
    while (t--)
    {
        solve();
    }

    return 0;
}